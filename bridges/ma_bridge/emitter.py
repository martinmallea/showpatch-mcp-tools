"""
Emisión hacia grandMA3: mensajes OSC y plugin Lua autocontenido.

- ``osc_messages()`` reutiliza ``core.commands.to_ma3`` para no duplicar la
  sintaxis nativa: un mensaje por comando, ``/gma3/cmd`` con un único argumento
  string.
- ``lua_script()`` genera un plugin MA3 válido (cabecera ``-- generated by
  showpatch``, cuerpo ``return function()`` y una llamada ``gma.cmd(...)``
  por comando). No hay E/S ni ``os``: el script se devuelve como string y el
  llamador decide dónde guardarlo.

El escapado Lua es obligatorio: una comilla o una barra invertida sin escapar
rompe el plugin en consola. Orden de escape: primero ``\\`` (para no duplicar
los backslashes introducidos por los pasos siguientes), después ``"``, y por
último los saltos de línea, que se convierten en ``\\n`` literales para que cada
comando ocupe exactamente una línea de código.
"""

from core.commands import to_ma3

DEFAULT_OSC_PREFIX = "/gma3/cmd"
GENERATED_HEADER = "-- generated by showpatch"


def escape_lua_string(text) -> str:
    """Escapa un string para incrustarlo entre comillas dobles en Lua."""
    escaped = str(text).replace("\\", "\\\\")
    escaped = escaped.replace('"', '\\"')
    escaped = escaped.replace("\r\n", "\\n")
    escaped = escaped.replace("\n", "\\n")
    escaped = escaped.replace("\r", "\\n")
    return escaped


def osc_messages(show: dict, prefix: str = DEFAULT_OSC_PREFIX) -> list:
    """Devuelve un mensaje OSC por comando MA3: ``{"address", "args"}``."""
    return [{"address": prefix, "args": [command]} for command in to_ma3(show)]


def lua_script(show: dict, macro_name) -> str:
    """Genera un plugin MA3 completo que ejecuta el show comando a comando."""
    name = escape_lua_string(macro_name)
    lines = [
        GENERATED_HEADER,
        f'-- macro: "{name}"',
        "-- ejecutar desde Plugin Pool (Trigger: Manual)",
        "",
        "return function()",
    ]
    for command in to_ma3(show):
        lines.append(f'    gma.cmd("{escape_lua_string(command)}")')
    lines.append("end")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import json
